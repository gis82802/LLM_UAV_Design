import socket

# -------------------------------
# 設定要連線的伺服器 IP 和 Port
# -------------------------------
# IP 可是你自己的機器，也可能是遠端 server（例如放在 Docker 裡）
host = "192.168.2.102"  # 這裡請確認是 server 的 IP (192.168.2.100/192.168.2.102)
port = 8888             # 必須與 server 監聽的 port 相同

# -------------------------------
# 建立 TCP socket
# -------------------------------
# 預設使用 IPv4 + TCP，所以這裡等同於：
# socket.socket(socket.AF_INET, socket.SOCK_STREAM)
s = socket.socket()

# -------------------------------
# 嘗試連線到伺服器
# -------------------------------
s.connect((host, port))

# -------------------------------
# 傳送訊息給 server
# -------------------------------
s.sendall(b"Hello from Docker!")  # 傳送 bytes 資料

# -------------------------------
# 關閉 socket
# -------------------------------
s.close()
